def print_investigation_report(report):
    """Display the RazorGuard investigation report."""

    print("\n")
    print("=" * 70)
    print("RAZORGUARD AI - AI INVESTIGATION REPORT")
    print("=" * 70)

    print(
        f"\nTransaction ID: "
        f"{report['transaction_id']}"
    )

    print(
        f"Transaction Amount: "
        f"₹{report['transaction_amount']:,.2f}"
    )

    print(
        f"\nFraud Probability: "
        f"{report['fraud_probability']:.2f}%"
    )

    print(
        f"Risk Score: "
        f"{report['risk_score']}/100"
    )

    print(
        f"Risk Level: "
        f"{report['risk_level']}"
    )

    # -----------------------------------------------------
    # Strong evidence
    # -----------------------------------------------------

    print("\n" + "-" * 70)
    print("PRIMARY RISK EVIDENCE")
    print("-" * 70)

    if report["strong_signals"]:

        for index, signal in enumerate(
            report["strong_signals"],
            start=1
        ):

            print(f"{index}. {signal}")

    else:

        print("No primary risk evidence detected.")

    # -----------------------------------------------------
    # Supporting evidence
    # -----------------------------------------------------

    print("\n" + "-" * 70)
    print("SUPPORTING RISK EVIDENCE")
    print("-" * 70)

    if report["supporting_signals"]:

        for index, signal in enumerate(
            report["supporting_signals"],
            start=1
        ):

            print(f"{index}. {signal}")

    else:

        print("No supporting risk evidence detected.")

    # -----------------------------------------------------
    # Primary concern
    # -----------------------------------------------------

    print("\n" + "-" * 70)
    print("PRIMARY CONCERN")
    print("-" * 70)

    print(report["primary_concern"])

    # -----------------------------------------------------
    # Assessment
    # -----------------------------------------------------

    print("\n" + "-" * 70)
    print("AI ASSESSMENT")
    print("-" * 70)

    print(report["assessment"])

    # -----------------------------------------------------
    # Recommendation
    # -----------------------------------------------------

    print("\n" + "-" * 70)
    print("RECOMMENDED ACTION")
    print("-" * 70)

    print(report["recommended_action"])

    # -----------------------------------------------------
    # Confidence
    # -----------------------------------------------------

    print("\n" + "-" * 70)
    print("CONFIDENCE")
    print("-" * 70)

    print(report["confidence"])

    # -----------------------------------------------------
    # Limitation
    # -----------------------------------------------------

    print("\n" + "-" * 70)
    print("LIMITATION")
    print("-" * 70)

    print(report["limitations"])

    print("\n" + "=" * 70)


